const { chromium } = require('/home/tobi/wondertours_web_site/node_modules/playwright');
(async () => {
  const browser = await chromium.launch({ headless: true });
  const page = await browser.newPage();
  page.on('console', m => console.log('CONSOLE', m.text()));
  await page.goto('https://leanie.vercel.app/#settings', { waitUntil:'domcontentloaded' });
  await page.waitForTimeout(3000);
  await page.getByPlaceholder('Email').fill(`ca-${Date.now()}@example.com`);
  await page.getByPlaceholder('Password').fill('TestPassword123!');
  await page.getByRole('button', { name:'Sign up' }).click();
  await page.waitForTimeout(6000);
  await page.getByRole('button', { name:/New Project/ }).click();
  await page.waitForTimeout(1000);
  await page.getByPlaceholder('e.g. Validate a new service concept').fill('P3 Shared Plan');
  await page.getByPlaceholder('What decision, problem, or opportunity should the Council examine?').fill('QA P3 verifies editing filtering drag drop and PDF.');
  await page.getByPlaceholder('What has led to this point? What evidence or uncertainty already exists?').fill('Automated QA run on production Neon backend.');
  await page.getByPlaceholder('What would a useful result make possible?').fill('Evidence for P3 completion.');
  await page.getByText('Continue').first().click();
  await page.waitForTimeout(2000);
  await page.getByText('Continue').first().click();
  await page.waitForTimeout(2000);
  await page.locator('button', { hasText:'Analyze' }).first().click();
  await page.waitForURL('**/#results', { timeout: 180000 });
  await page.getByRole('button', { name: 'Open project plan' }).click();
  await page.waitForURL('**/#plan', { timeout: 20000 });
  await page.waitForTimeout(3000);
  await page.locator('.title-input').first().fill('Account A initial title');
  await page.waitForTimeout(2000);
  await page.getByRole('button', { name: 'Create share link' }).click();
  await page.waitForTimeout(6000);
  const shareText = await page.locator('body').innerText();
  const shareMatch = shareText.match(/https?:\/\/[^\s]*#shared\/[0-9a-f-]+/i);
  if (!shareMatch) throw new Error('No share link found');
  const shareUrl = shareMatch[0];
  console.log('SHARE URL:', shareUrl);
  const pageB = await browser.newPage();
  await pageB.goto(shareUrl, { waitUntil:'domcontentloaded' });
  await pageB.waitForTimeout(10000);
  const bBefore = await pageB.locator('.title-input').first().inputValue();
  console.log('B before:', bBefore);
  await pageB.locator('.title-input').first().fill('Account B collaboration edit');
  await pageB.waitForTimeout(5000);
  for (let i=0;i<10;i++) {
    await page.waitForTimeout(4000);
    const t = await page.locator('.title-input').first().inputValue();
    console.log('A attempt', i+1, t);
    if (t === 'Account B collaboration edit') break;
  }
  const aFinal = await page.locator('.title-input').first().inputValue();
  console.log('A final:', aFinal);
  if (aFinal !== 'Account B collaboration edit') process.exit(1);
  console.log('COLLAB PASS');
  await browser.close();
})().catch(err => { console.error('COLLAB FAIL', err); process.exit(1); });