const dictionaries: Record<Lang, Record<DictKey, string>> = { en, fr }

export function translate(
  lang: Lang,
  key: DictKey,
  vars?: Record<string, string | number>,
): string {
  let text = dictionaries[lang]?.[key] ?? dictionaries.en[key] ?? key
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.split(`{${k}}`).join(String(v))
    }
  }
  return text
}

export function formatDate(value: string, lang: Lang): string {
  return new Intl.DateTimeFormat(lang === "fr" ? "fr" : "en", {
    day: "numeric",
    month: "short",
    year: "numeric",
  }).format(new Date(value))
}

export function formatToday(lang: Lang): string {
  return new Intl.DateTimeFormat(lang === "fr" ? "fr" : "en", {
    weekday: "long",
    month: "long",
    day: "numeric",
  }).format(new Date())
}

const LANG_KEY = "leanie-lang"

interface LangContextValue {
  lang: Lang
  setLang: (lang: Lang) => void
  t: (key: DictKey, vars?: Record<string, string | number>) => string
}

const LangContext = createContext<LangContextValue | null>(null)

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(() => {
    try {
      return localStorage.getItem(LANG_KEY) === "fr" ? "fr" : "en"
    } catch {
      return "en"
    }
  })

  useEffect(() => {
    try {
      localStorage.setItem(LANG_KEY, lang)
    } catch {
      // storage may be unavailable; keep in-memory preference
    }
    document.documentElement.lang = lang
  }, [lang])

  const value = useMemo<LangContextValue>(
    () => ({ lang, setLang, t: (key, vars) => translate(lang, key, vars) }),
    [lang],
  )

  return <LangContext.Provider value={value}>{children}</LangContext.Provider>
}

export function useLang(): LangContextValue {
  const value = useContext(LangContext)
  if (!value) throw new Error("useLang must be used inside LangProvider")
  return value
}
